package main

import (
	"bytes"
	"fmt"
	"io"
	"regexp"
	"slices"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
	"github.com/spf13/pflag"

	"phenix/cmd"
)

const (
	indexFile     = "index.md"
	generatedNote = "<!-- Generated by `make cli-docs` from the phenix command tree. Do not edit. -->"
)

var (
	slugDrop = regexp.MustCompile(`[^\w\s-]`)
	slugJoin = regexp.MustCompile(`[-\s]+`)
)

// page is one generated reference page: its file name, its title in the nav, and its Markdown.
type page struct {
	File  string
	Title string
	Body  string
}

// render returns the reference pages for root: an index page for root itself, whose options are
// the global flags, and one page for each top-level command and everything under it.
func render(root *cobra.Command) ([]page, error) {
	defer useDocDefaults(root)()
	defer useTextBlocks(root)()

	targets := make(map[string]string)

	visit(root, func(c *cobra.Command) { targets[cobraLink(c)] = target(c) })

	link := func(name string) string {
		if t, ok := targets[name]; ok {
			return t
		}

		return name
	}

	var index bytes.Buffer

	fmt.Fprintf(&index, "# CLI Reference\n\n%s\n\n", generatedNote)
	fmt.Fprintf(&index, "Every `%s` command, generated from its source. Each top-level command has its own page,"+
		" and the options of `%s` itself are global flags that every command accepts.\n\n", root.Name(), root.Name())

	if err := genMarkdown(root, &index, link); err != nil {
		return nil, err
	}

	pages := []page{{File: indexFile, Title: "Overview", Body: tidy(index.String())}}

	// Each page states once that the global flags apply, rather than every command listing them.
	defer hideFlags(root.PersistentFlags())()

	for _, top := range available(root) {
		var (
			buf bytes.Buffer
			err error
		)

		fmt.Fprintf(&buf, "# %s\n\n%s\n\n", top.CommandPath(), generatedNote)
		fmt.Fprintf(&buf, "Every command on this page also accepts the [global flags](%s#options).\n\n", indexFile)

		visit(top, func(c *cobra.Command) {
			if err == nil {
				err = genMarkdown(c, &buf, link)
			}
		})

		if err != nil {
			return nil, err
		}

		pages = append(pages, page{File: top.Name() + ".md", Title: top.CommandPath(), Body: tidy(buf.String())})
	}

	return pages, nil
}

func genMarkdown(c *cobra.Command, w io.Writer, link func(string) string) error {
	c.DisableAutoGenTag = true

	if err := doc.GenMarkdownCustom(c, w, link); err != nil {
		return fmt.Errorf("rendering %s: %w", c.CommandPath(), err)
	}

	return nil
}

// visit calls fn for c and then for each command under it that the reference shows, depth first.
func visit(c *cobra.Command, fn func(*cobra.Command)) {
	fn(c)

	for _, child := range available(c) {
		visit(child, fn)
	}
}

// available returns, by name, the subcommands of c that cobra documents.
func available(c *cobra.Command) []*cobra.Command {
	var children []*cobra.Command

	for _, child := range c.Commands() {
		if child.IsAvailableCommand() && !child.IsAdditionalHelpTopicCommand() {
			children = append(children, child)
		}
	}

	slices.SortFunc(children, func(a, b *cobra.Command) int { return strings.Compare(a.Name(), b.Name()) })

	return children
}

// cobraLink is the file name cobra links a command by.
func cobraLink(c *cobra.Command) string {
	return strings.ReplaceAll(c.CommandPath(), " ", "_") + ".md"
}

// target is where a command is documented: its page, and the heading on it below the top.
func target(c *cobra.Command) string {
	if !c.HasParent() {
		return indexFile
	}

	top := c
	for top.Parent().HasParent() {
		top = top.Parent()
	}

	if top == c {
		return c.Name() + ".md"
	}

	return top.Name() + ".md#" + slug(c.CommandPath())
}

// slug is the anchor mkdocs gives a heading, as Python-Markdown's toc extension makes it from an
// ASCII heading such as a command path.
func slug(heading string) string {
	s := strings.ToLower(strings.TrimSpace(slugDrop.ReplaceAllString(heading, "")))

	return slugJoin.ReplaceAllString(s, "-")
}

// useDocDefaults shows each flag annotated with cmd.DocDefaultAnnotation with that default
// instead of its own, until the returned function restores them.
func useDocDefaults(root *cobra.Command) func() {
	flags := make(map[*pflag.Flag]bool)

	visit(root, func(c *cobra.Command) {
		c.Flags().VisitAll(func(f *pflag.Flag) { flags[f] = true })
		c.PersistentFlags().VisitAll(func(f *pflag.Flag) { flags[f] = true })
	})

	var restore []func()

	for f := range flags {
		def, ok := f.Annotations[cmd.DocDefaultAnnotation]
		if !ok || len(def) == 0 {
			continue
		}

		value, usage := f.DefValue, f.Usage
		restore = append(restore, func() { f.DefValue, f.Usage = value, usage })

		f.DefValue = ""
		f.Usage = fmt.Sprintf("%s (default: %s)", usage, def[0])
	}

	return func() {
		for _, fn := range restore {
			fn()
		}
	}
}

// useTextBlocks shows each command's synopsis and examples as the plain text help prints them, in
// code blocks without their common indentation, until the returned function restores them.
func useTextBlocks(root *cobra.Command) func() {
	var restore []func()

	visit(root, func(c *cobra.Command) {
		long, example := c.Long, c.Example
		restore = append(restore, func() { c.Long, c.Example = long, example })

		c.Example = dedent(example)
		if text := dedent(long); text != "" {
			fence := "```"
			for strings.Contains(text, fence) {
				fence += "`"
			}

			c.Long = fence + "text\n" + text + "\n" + fence
		}
	})

	return func() {
		for _, fn := range restore {
			fn()
		}
	}
}

// dedent drops the blank lines around text, trailing spaces, and the indentation its lines share.
func dedent(text string) string {
	lines := strings.Split(text, "\n")

	var (
		indent string
		first  = true
	)

	for _, line := range lines {
		if strings.TrimSpace(line) == "" {
			continue
		}

		lead := line[:len(line)-len(strings.TrimLeft(line, " \t"))]
		if first {
			indent, first = lead, false

			continue
		}

		for !strings.HasPrefix(lead, indent) {
			indent = indent[:len(indent)-1]
		}
	}

	for i, line := range lines {
		lines[i] = strings.TrimRight(strings.TrimPrefix(line, indent), " \t")
	}

	start, end := 0, len(lines)
	for start < end && lines[start] == "" {
		start++
	}

	for end > start && lines[end-1] == "" {
		end--
	}

	return strings.Join(lines[start:end], "\n")
}

// hideFlags hides every flag in fs until the returned function restores them.
func hideFlags(fs *pflag.FlagSet) func() {
	hidden := make(map[*pflag.Flag]bool)

	fs.VisitAll(func(f *pflag.Flag) {
		hidden[f] = f.Hidden
		f.Hidden = true
	})

	return func() {
		for f, h := range hidden {
			f.Hidden = h
		}
	}
}

// tidy makes cobra's Markdown pass the repository's Markdown lint: it names the language of
// unlabeled code blocks, drops trailing and repeated blank lines, and the tabs in link lists.
func tidy(markdown string) string {
	var (
		lines   = make([]string, 0, strings.Count(markdown, "\n")+1)
		inFence bool
		blank   bool
	)

	for line := range strings.SplitSeq(markdown, "\n") {
		line = strings.TrimRight(line, " \t")

		switch {
		case strings.HasPrefix(line, "```"):
			if !inFence && line == "```" {
				line = "```text"
			}

			inFence = !inFence
		case inFence:
		case line == "":
			if blank {
				continue
			}
		default:
			line = strings.Replace(line, ")\t - ", ") - ", 1)
		}

		blank = line == "" && !inFence
		lines = append(lines, line)
	}

	return strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n"
}
