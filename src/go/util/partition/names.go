// mbrTypeName returns the name of MBR partition type t, or "" for a type phenix does not know.
func mbrTypeName(t byte) string {
	return mbrTypes[t]
}

// gptTypeName returns the name of the GPT partition type GUID id, in upper case, or "" for a type phenix does not
// know.
func gptTypeName(id string) string {
	return gptTypes[id]
}
