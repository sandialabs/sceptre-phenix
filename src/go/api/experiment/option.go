const defaultBridgeName = "phenix"

type CreateOption func(*createOptions)

type createOptions struct {
	name            string
	annotations     map[string]string
	nodeAnnotations map[string]any
	topology        string
	scenario        string
	disabledApps    []string
	vlanMin         int
	vlanMax         int
	vlanAliases     map[string]int
	schedules       map[string]string
	baseDir         string
	deployMode      common.DeploymentMode
	useGREMesh      bool
	defaultBridge   string
	baseDirRoot     string
}

func newCreateOptions(opts ...CreateOption) createOptions {
	o := createOptions{ //nolint:exhaustruct // functional options pattern
		deployMode: common.DeployMode,
		useGREMesh: common.UseGREMesh,
	}

	for _, opt := range opts {
		opt(&o)
	}

	if o.baseDir == "" {
		o.baseDir = common.PhenixBase + "/experiments/" + o.name
	}

	if o.defaultBridge == "" {
		o.defaultBridge = defaultBridgeName
	}

	return o
}

func CreateWithName(n string) CreateOption {
	return func(o *createOptions) {
		o.name = n
	}
}

