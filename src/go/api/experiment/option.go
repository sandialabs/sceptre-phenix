type StartOption func(*startOptions)

type startOptions struct {
	name    string
	dryrun  bool
	vlanMin int
	vlanMax int
	errChan chan error

	// Option to treat all errors generated by minimega as warnings when launching
	// an experiment.
	mmErrAsWarn bool

	// a dry run that does not record the start, so the experiment stays stopped
	keepStopped bool
	result      *StartResult
}

// StartResult is what Start reports of a start that StartWithResult asked for.
type StartResult struct {
	// MMScript is the path of the minimega script that the start wrote.
	MMScript string
}

func newStartOptions(opts ...StartOption) startOptions {
	var o startOptions

	for _, opt := range opts {
		opt(&o)
	}

	return o
}

func StartWithName(n string) StartOption {
	return func(o *startOptions) {
		o.name = n
	}
}

func StartWithDryRun(d bool) StartOption {
	return func(o *startOptions) {
		o.dryrun = d
	}
}

func StartWithVLANMin(m int) StartOption {
	return func(o *startOptions) {
		o.vlanMin = m
	}
}

func StartWithVLANMax(m int) StartOption {
	return func(o *startOptions) {
		o.vlanMax = m
	}
}

func StartWithErrorChannel(c chan error) StartOption {
	return func(o *startOptions) {
		o.errChan = c
	}
}

func StartWithMMErrorsAsWarnings(w bool) StartOption {
	return func(o *startOptions) {
		o.mmErrAsWarn = w
	}
}

// StartWithKeepStopped has a dry run (StartWithDryRun) do all of the start but record it: the store does not mark
// the experiment as started, so it stays stopped, and the start hooks do not run. A start that is not a dry run
// ignores it.
func StartWithKeepStopped(k bool) StartOption {
	return func(o *startOptions) {
		o.keepStopped = k
	}
}

// StartWithResult has Start fill r with what it did.
func StartWithResult(r *StartResult) StartOption {
	return func(o *startOptions) {
		o.result = r
	}
}

